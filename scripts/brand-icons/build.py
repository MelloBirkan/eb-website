"""Renders the EvenBetter EB icon set from one geometry and one palette.

Run from the repo root:  python3 scripts/brand-icons/build.py
Needs Pillow (pip install pillow) and Playwright's Chromium (node -e "require('playwright')").

Writes:
  components/site/brand.ts           paths and colors for BrandMark and the OG image
  app/icon.svg, app/favicon.ico      browser tab (heavier "small" cut, legible at 16 px)
  app/apple-icon.png                 iOS home screen, 180 px, square (iOS rounds it)
  public/brand/icon-192.png, icon-512.png, icon-maskable-512.png   web manifest
  public/brand/evenbetter-icon.svg   tile, for slides and docs
  public/brand/evenbetter-mark.svg   letters only, for dark backgrounds
"""
import json
import os
import subprocess
import sys
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
from eb import fmt, glyph  # noqa: E402

TILE, E_FILL, B_FILL = "#0b1a18", "#b6efd9", "#3fa38c"
RADIUS = 0.22  # tile corner, share of the side
FULL = dict(H=300, w=62, gap=10)  # app icons and large marks: thin cut between E and B
SMALL = dict(H=340, w=72, gap=0)  # favicon and UI sizes: heavier, no cut


def centered(scale=1.0, H=300, w=62, gap=0):
    H, w, gap = H * scale, w * scale, gap * scale
    _, _, W = glyph(H=H, w=w, gap=gap)
    return glyph(H=H, w=w, gap=gap, ox=(512 - W) / 2, oy=(512 - H) / 2)


def tile_svg(e, b, rx):
    t = f'<rect width="512" height="512" rx="{fmt(rx)}" fill="{TILE}"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">{t}'
        f'<path fill="{B_FILL}" fill-rule="evenodd" d="{b}"/><path fill="{E_FILL}" d="{e}"/></svg>\n'
    )


def main():
    os.chdir(os.path.join(HERE, "..", ".."))
    full_e, full_b, _ = centered(**FULL)
    small_e, small_b, _ = centered(**SMALL)
    mask_e, mask_b, _ = centered(scale=0.86, **FULL)  # inside Android's 80% safe circle

    icon = tile_svg(small_e, small_b, 512 * RADIUS)
    tile = tile_svg(full_e, full_b, 512 * RADIUS)
    square = tile_svg(full_e, full_b, 0)
    maskable = tile_svg(mask_e, mask_b, 0)

    os.makedirs("public/brand", exist_ok=True)
    open("app/icon.svg", "w").write(icon)
    open("public/brand/evenbetter-icon.svg", "w").write(tile)
    e, b, W = glyph(**FULL)
    H = FULL["H"]
    open("public/brand/evenbetter-mark.svg", "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {fmt(W)} {H}" width="{fmt(W)}" height="{H}">'
        f'<path fill="{B_FILL}" fill-rule="evenodd" d="{b}"/><path fill="{E_FILL}" d="{e}"/></svg>\n'
    )

    with tempfile.TemporaryDirectory() as tmp:
        jobs = [
            dict(svg=icon, size=s, out=f"{tmp}/fav{s}.png") for s in (16, 32, 48)
        ] + [
            dict(svg=square, size=180, out="app/apple-icon.png"),
            dict(svg=tile, size=192, out="public/brand/icon-192.png"),
            dict(svg=tile, size=512, out="public/brand/icon-512.png"),
            dict(svg=maskable, size=512, out="public/brand/icon-maskable-512.png"),
        ]
        json.dump(jobs, open(f"{tmp}/jobs.json", "w"))
        subprocess.run(["node", os.path.join(HERE, "raster.js"), f"{tmp}/jobs.json"], check=True)
        favs = [Image.open(f"{tmp}/fav{s}.png").convert("RGBA") for s in (16, 32, 48)]
        favs[2].save("app/favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)], append_images=favs[:2])
    # iOS fills transparency with black, so keep the apple icon opaque.
    Image.open("app/apple-icon.png").convert("RGB").save("app/apple-icon.png", optimize=True)

    open("components/site/brand.ts", "w").write(f"""/* The EvenBetter EB monogram: a B whose left part (the spine and the arm stubs) is the E.
   Paths sit on a 512 x 512 tile. `full` has a thin cut between the letters and is drawn for
   app icons and large marks; `small` is heavier, with no cut, so it still reads at 16 px.
   Generated by scripts/brand-icons/build.py, together with app/icon.svg, app/favicon.ico,
   app/apple-icon.png and public/brand/*. Change the geometry or colors there, not here. */

export const BRAND_COLORS = {{
  tile: '{TILE}',
  e: '{E_FILL}',
  b: '{B_FILL}',
}} as const

export const BRAND_PATHS = {{
  full: {{
    e: '{full_e}',
    b: '{full_b}',
  }},
  small: {{
    e: '{small_e}',
    b: '{small_b}',
  }},
}} as const

/* Tile corner radius as a share of its side, close to the iOS app icon curve. */
export const BRAND_TILE_RADIUS = {RADIUS}
""")
    print("brand icons written")


if __name__ == "__main__":
    main()
